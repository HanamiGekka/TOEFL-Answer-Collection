import { describe, expect, it } from 'vitest';
import { prepareRecoverySession } from '../recovery';
import { defaultShortcutBindings, migrateShortcutBindings, SHORTCUT_REGISTRY } from '../shortcutRegistry';
import golden from './fixtures/v1.0.0-dynamic-v6.json';
import { serializeSessionForPersistence, toPersistedMilliseconds } from '../persistedTime';
import { buildSessionExportBundle } from '../sessionExport';
import { buildSessionRecordIndex } from '../exporters';
import { filterAndPageRecords } from '../recordManager';

describe('R009 current product compatibility boundary', () => {
  it('ignores obsolete saved shortcut keys while preserving valid custom bindings', () => {
    const saved = { ...defaultShortcutBindings(), next_question: 'Alt+N', speaking_start: 'Alt+Enter', speaking_retry: 'F9' };
    const migrated = migrateShortcutBindings(saved);
    expect(migrated.next_question).toBe('Alt+N');
    expect(Object.keys(migrated)).not.toContain('speaking_start');
    expect(SHORTCUT_REGISTRY.every((definition) => !definition.action_id.startsWith('speaking_'))).toBe(true);
  });

  it.each([2, 3, 4, 5])('rejects unsupported schema %i without migration', (session_schema_version) => {
    const result = prepareRecoverySession({ session_schema_version });
    expect(result).toMatchObject({ ok: false, code: 'UNSUPPORTED_SESSION_SCHEMA' });
  });

  it('reads the synthetic official v1.0.0 v6 snapshot through Recovery, indexing and safe export', () => {
    // Golden generated by the v1.0.0 source at 441f4c8, using synthetic answers only.
    const original = JSON.stringify(golden);
    const result = prepareRecoverySession(golden);
    expect(result.ok).toBe(true);
    if (!result.ok) throw new Error(result.diagnostic);
    expect(result.resume_policy).toEqual({ paused: true, reuse_monotonic_anchor: false });
    expect(result.session.source_relative_path).toBe('Synthetic.01');
    expect(result.session.questions.map((item) => item.id)).toEqual(['R1', 'L1', 'W1']);
    const persisted = serializeSessionForPersistence(result.session);
    expect(persisted.active_ms).toBe(2500);
    expect(prepareRecoverySession(JSON.stringify(persisted)).ok).toBe(true);
    const exported = buildSessionExportBundle(persisted, []);
    const index = buildSessionRecordIndex(persisted, exported.directory, Object.keys(exported.files));
    expect(index.section_item_counts).toEqual({ Reading: 1, Listening: 1, Writing: 1 });
    expect(filterAndPageRecords([index], { page: 1 }).total).toBe(1);
    expect(Object.keys(exported.files)).toEqual(expect.arrayContaining(['Reading.md', 'Listening.md', 'Writing.md']));
    expect(exported.files['answers.json']).not.toMatch(/source_path|source_relative_path|question_body|standard_answer/);
    expect(JSON.stringify(golden)).toBe(original);
  });

  it('keeps the integer persistence boundary after removing old-format migrations', () => {
    expect(toPersistedMilliseconds(1.6, 'synthetic')).toBe(2);
    for (const value of [null, NaN, Infinity, -1, Number.MAX_SAFE_INTEGER + 1]) {
      expect(() => toPersistedMilliseconds(value, 'synthetic')).toThrow();
    }
    const result = prepareRecoverySession({ ...golden, modules: [{}] });
    expect(result).toMatchObject({ ok: false, code: 'INVALID_SNAPSHOT' });
  });
});
